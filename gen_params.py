#!/usr/bin/env python3
"""Generate params.vh for timing_test.v and timing_test2.v.

Picks MMCM settings for the requested frequency from the Cmod A7's 12 MHz
clock, and computes the expected result of the ARX computation so the FPGA
can check itself.

    python3 gen_params.py --freq 150 --rounds 4 > params.vh
"""
import argparse
import sys

CLKIN_MHZ = 12.0
VCO_MIN, VCO_MAX = 600.0, 1200.0      # Artix-7 -1 speed grade
MASK32 = 0xFFFFFFFF
SEED_A, SEED_B = 0x243F6A88, 0x85A308D3   # digits of pi; any value works
LOG2_ITERS = 20                            # 2^20 clock cycles of computation


def rotl32(x, n):
    return ((x << n) | (x >> (32 - n))) & MASK32


def arx(a, b, rounds):
    # Must match the arx function in timing_test.v exactly.
    for _ in range(rounds):
        a = (a + b) & MASK32
        b = rotl32(b, 7) ^ a
    return a, b


def pick_mmcm(freq, clkin=CLKIN_MHZ):
    """Return (mult, divide, actual_mhz) with DIVCLK_DIVIDE = 1."""
    best = None
    # CLKFBOUT_MULT_F, steps of 0.125. UG472 allows up to 64, but nextpnr releases
    # without the lk_table fix reject anything above 63, so stay at or below 63.
    for mult8 in range(2 * 8, 63 * 8 + 1):
        mult = mult8 / 8
        vco = clkin * mult
        if not VCO_MIN <= vco <= VCO_MAX:
            continue
        # CLKOUT0_DIVIDE_F: 1, or 2.000 to 128.000 in steps of 0.125
        # (Vivado's DRC rejects fractional values between 1 and 2).
        for div8 in [8] + list(range(2 * 8, 128 * 8 + 1)):
            div = div8 / 8
            out = vco / div
            err = abs(out - freq)
            # Prefer exact matches, then integer settings, then a lower VCO.
            key = (round(err, 6), mult != int(mult), div != int(div), vco)
            if best is None or key < best[0]:
                best = (key, mult, div, out)
    _, mult, div, out = best
    return mult, div, out


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--freq", type=float, required=True, help="target MHz")
    p.add_argument("--rounds", type=int, default=4, help="ARX rounds per clock")
    p.add_argument("--cascade", action="store_true",
                   help="two MMCMs: 12 -> 100 MHz, then 100 MHz -> the fast clock")
    p.add_argument("--corrupt", action="store_true",
                   help="flip one bit of EXPECTED_A (negative control: must show red)")
    args = p.parse_args()

    if args.cascade:
        mult, div = 50.0, 6.0                       # 12 * 50 / 6 = 100 MHz
        mult2, div2, actual = pick_mmcm(args.freq, clkin=100.0)
    else:
        mult, div, actual = pick_mmcm(args.freq)
    if abs(actual - args.freq) > 0.01:
        print(f"note: {args.freq} MHz not exact, using {actual:.3f} MHz",
              file=sys.stderr)

    a, b = SEED_A, SEED_B
    for _ in range(1 << LOG2_ITERS):
        a, b = arx(a, b, args.rounds)

    print(f"// Generated by gen_params.py --freq {args.freq} --rounds {args.rounds}")
    if args.cascade:
        print(f"// Fast clock: 12 MHz * {mult} / {div} = 100 MHz, then * {mult2} / {div2} "
              f"(VCO {100.0 * mult2:.0f} MHz) = {actual:.3f} MHz")
        print("`define CASCADE")
        print(f"`define MMCM2_MULT  {mult2:.3f}")
        print(f"`define MMCM2_DIV   {div2:.3f}")
    else:
        print(f"// Fast clock: 12 MHz * {mult} / {div} = {actual:.3f} MHz "
              f"(VCO {CLKIN_MHZ * mult:.0f} MHz)")
    print(f"`define MMCM_MULT   {mult:.3f}")
    print(f"`define MMCM_DIV    {div:.3f}")
    print(f"`define ROUNDS      {args.rounds}")
    print(f"`define LOG2_ITERS  {LOG2_ITERS}")
    print(f"`define SEED_A      32'h{SEED_A:08X}")
    print(f"`define SEED_B      32'h{SEED_B:08X}")
    if args.corrupt:
        a ^= 1
        print("// CORRUPTED: EXPECTED_A has bit 0 flipped, the design must show red")
    # timing_test2: one run is 2^LOG2_ITERS + 1 cycles, led[1] toggles every 256 runs
    toggle_s = 256 * ((1 << LOG2_ITERS) + 1) / (actual * 1e6)
    print(f"// timing_test2: led[1] toggles every {toggle_s:.4f} s "
          f"(10 toggles = {10 * toggle_s:.2f} s)")
    print(f"`define EXPECTED_A  32'h{a:08X}")
    print(f"`define EXPECTED_B  32'h{b:08X}")


if __name__ == "__main__":
    main()
